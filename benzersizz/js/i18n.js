const PREF = 'bz-lang';
let lang = localStorage.getItem(PREF) === 'ar' ? 'ar' : 'en';

export const i18n = {
  get lang() { return lang; },
  t(key) { return DICT[lang][key] ?? DICT.en[key] ?? key; },

  apply() {
    document.documentElement.lang = lang;
    document.body.classList.toggle('ar', lang === 'ar');
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const v = this.t(el.dataset.i18n);
      if (el.dataset.i18nHtml !== undefined) el.innerHTML = v;
      else el.textContent = v;
    });
    // overlays flip direction; nav/hud keep LTR chrome positions
    document.getElementById('overlays').dir = lang === 'ar' ? 'rtl' : 'ltr';
    const btn = document.getElementById('lang-toggle');
    if (btn) btn.textContent = lang === 'ar' ? 'EN' : 'ع';
  },

  toggle() {
    lang = lang === 'ar' ? 'en' : 'ar';
    localStorage.setItem(PREF, lang);
    this.apply();
    return lang;
  },
};
